local okCount = 0
local failCount = 0
local failedNames = {}

local function RF(...)
    local ok, ref = pcall(gui.Reference, ...)
    if ok then return ref end
    return nil
end

local function fail(name)
    failCount = failCount + 1
    if name and #failedNames < 12 then failedNames[#failedNames + 1] = tostring(name) end
end

local function SN(obj, name)
    if obj == nil then fail(name) return end
    if pcall(function() obj:SetName(name) end) then okCount = okCount + 1 else fail(name) end
end

local function SD(obj, text)
    if obj == nil then fail() return end
    if not pcall(function() obj:SetDescription(text) end) then fail() end
end

local function SO(obj, ...)
    local opts = { ... }
    if obj == nil then fail() return end
    if not pcall(function() obj:SetOptions((table.unpack or unpack)(opts)) end) then fail() end
end

local function FCR(parent, name)
    if parent == nil then return nil end
    for child in parent:Children() do
        if child:GetName() == name then return child end
        local found = FCR(child, name)
        if found then return found end
    end
    return nil
end

local function DumpGUI()
    local parts = {}
    local function walk(obj)
        parts[#parts + 1] = obj:GetName()
        for child in obj:Children() do walk(child) end
    end
    walk(RF())
    return table.concat(parts, "\n")
end

local function HasNonASCII(str)
    return str:find("[\128-\255]") ~= nil
end

